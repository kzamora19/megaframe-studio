const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const pixel=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4////fwAJ+wP9J6ofLwAAAABJRU5ErkJggg==','base64');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const errors=[];
 try{
  const page=await browser.newPage({viewport:{width:1400,height:950}});
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://127.0.0.1:4173/',{waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>document.querySelector('#draftStatus')?.textContent?.includes('Auto-save ready'));
  await page.locator('#createNewProject').click();
  await page.locator('[data-panel="1"]').click();
  await page.locator('#shapePreset').selectOption('rect');
  await page.locator('#photosInput').setInputFiles([{name:'photo-a.png',mimeType:'image/png',buffer:pixel},{name:'photo-b.png',mimeType:'image/png',buffer:pixel}]);
  await page.waitForFunction(()=>document.querySelector('#photoCount')?.textContent?.includes('2 photos'));
  await page.locator('[data-panel="4"]').click();
  await page.locator('#autoLighting').click();
  assert.equal(await page.locator('#filterPreset').inputValue(),'custom','Auto lighting should update the selected photo filters');
  assert.notEqual(await page.locator('#filterBrightness').inputValue(),'100','Auto lighting should modify brightness on a bright test image');
  await page.locator('[data-panel="5"]').click();
  await page.locator('#prepareAll').click();
  await page.locator('#exportGallery[open]').waitFor({timeout:60000});
  assert.equal(await page.locator('.exportFileCard').count(),2,'Two photos should have two export cards');
  assert.equal(await page.locator('.comparePair figure').count(),4,'Every export has before/after previews');
  await page.locator('#closeExportGallery').click();
  await page.locator('[data-panel="0"]').click();
  await page.locator('#saveTemplate').click();
  await page.locator('#actionModal[open]').waitFor();
  await page.locator('#actionModalInput').fill('v27 Test Campaign');
  await page.locator('#actionModalConfirm').click();
  await page.waitForFunction(()=>Array.from(document.querySelectorAll('#templateSelect option')).some(o=>o.textContent.includes('v27 Test Campaign')));
  await page.locator('#openFrameLibrary').click();
  const card=page.locator('#frameLibGrid .frameLibCard').filter({hasText:'v27 Test Campaign'});
  await card.locator('.organizeFrame').click();
  await page.locator('#actionModalInput').fill('First Megasaver');
  await page.locator('#actionModalConfirm').click();
  await page.locator('#actionModalInput').fill('Holiday');
  await page.locator('#actionModalConfirm').click();
  await page.waitForFunction(()=>Array.from(document.querySelectorAll('#frameLibFolder option')).some(o=>o.value==='First Megasaver'));
  await page.locator('#frameLibFolder').selectOption('First Megasaver');
  await page.locator('#frameLibCategory').selectOption('Holiday');
  assert.equal(await page.locator('#frameLibGrid .frameLibCard').count(),1,'Folder/category filters should narrow the library');
  await page.locator('#closeFrameLibrary').click();
  const phone=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  phone.on('pageerror',error=>errors.push(error.message));
  await phone.goto('http://127.0.0.1:4173/',{waitUntil:'domcontentloaded'});
  await phone.waitForFunction(()=>document.querySelector('#draftStatus')?.textContent?.includes('Auto-save ready'));
  await phone.locator('#createNewProject').click();
  await phone.locator('#mobileDrawerToggle').click();
  assert.equal(await phone.locator('#mobileDrawerToggle').getAttribute('aria-expanded'),'false');
  assert.equal(await phone.locator('#pinNav').isVisible(),false);
  await phone.locator('#mobileDrawerToggle').click();
  assert.equal(await phone.locator('#pinNav').isVisible(),true);
  assert.deepEqual(errors,[],'Unexpected browser exceptions: '+errors.join('; '));
  console.log('PASS: auto lighting, before/after batch previews, local template folders/categories and mobile drawer.');
 }finally{await browser.close()}
})().catch(err=>{console.error(err);process.exitCode=1});
